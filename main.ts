// Convert char to lowercase-uppercase mapping (font only has upper)
function charFor(ch: string): string {
  const upper = ch.toUpperCase();
  return FONT[upper] ? upper : ch;
}

// ───────── CRC32 ─────────
const crcTable = new Uint32Array(256);
for (let i = 0; i < 256; i++) {
  let c = i;
  for (let j = 0; j < 8; j++) c = (c & 1) ? (0xEDB88320 ^ (c >>> 1)) : (c >>> 1);
  crcTable[i] = c;
}
function crc32(buf: Buffer): number {
  let c = 0xFFFFFFFF;
  for (let i = 0; i < buf.length; i++) c = (c >>> 8) ^ crcTable[(c ^ buf[i]) & 0xFF];
  return (c ^ 0xFFFFFFFF) >>> 0;
}

// ───────── PNG encoder (color type 2 = RGB 8-bit) ─────────
function chunk(type: string, data: Buffer): Buffer {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length, 0);
  const typeBuf = Buffer.from(type, 'ascii');
  const crcBuf = Buffer.concat([typeBuf, data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(crcBuf) >>> 0, 0);
  return Buffer.concat([len, typeBuf, data, crc]);
}

function encodePNG(width: number, height: number, pixels: Buffer): Buffer {
  const signature = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8;  // bit depth
  ihdr[9] = 2;  // color type: RGB
  ihdr[10] = 0; // compression
  ihdr[11] = 0; // filter
  ihdr[12] = 0; // interlace

  // Build raw scanlines: filter byte (0) + RGB per pixel
  const rowBytes = width * 3;
  const rawParts: Buffer[] = [];
  for (let y = 0; y < height; y++) {
    const row = Buffer.alloc(rowBytes + 1);
    row[0] = 0; // no filter
    pixels.copy(row, 1, y * rowBytes, (y + 1) * rowBytes);
    rawParts.push(row);
  }
  const raw = Buffer.concat(rawParts);
  const compressed = zlib.deflateRawSync(raw, { level: 9 });

  const idat = chunk('IDAT', compressed);
  const iend = chunk('IEND', Buffer.alloc(0));

  return Buffer.concat([
    signature,
    chunk('IHDR', ihdr),
    idat,
    iend,
  ]);
}

// ───────── Tiny canvas ─────────
class Canvas {
  width: number;
  height: number;
  data: Buffer;

  constructor(w: number, h: number) {
    this.width = w;
    this.height = h;
    this.data = Buffer.alloc(w * h * 3, 0);
  }

  setPixel(x: number, y: number, r: number, g: number, b: number): void {
    if (x < 0 || x >= this.width || y < 0 || y >= this.height) return;
    const i = (y * this.width + x) * 3;
    this.data[i] = r;
    this.data[i + 1] = g;
    this.data[i + 2] = b;
  }

  fillRect(x: number, y: number, w: number, h: number, r: number, g: number, b: number): void {
    for (let dy = 0; dy < h; dy++) {
      for (let dx = 0; dx < w; dx++) {
        this.setPixel(x + dx, y + dy, r, g, b);
      }
    }
  }

  drawText(x: number, y: number, text: string, r: number, g: number, b: number, scale: number = 1): void {
    let cx = x;
    for (let i = 0; i < text.length; i++) {
      const ch = charFor(text[i]);
      const rows = FONT[ch];
      if (!rows) { cx += 6 * scale; continue; }
      for (let ry = 0; ry < 7; ry++) {
        const bits = rows[ry];
        for (let bx = 0; bx < 5; bx++) {
          if (bits & (1 << (4 - bx))) {
            for (let sy = 0; sy < scale; sy++) {
              for (let sx = 0; sx < scale; sx++) {
                this.setPixel(cx + bx * scale + sx, y + ry * scale + sy, r, g, b);
              }
            }
          }
        }
      }
      cx += 6 * scale; // 5px char + 1px spacing
    }
  }

  textWidth(text: string, scale: number = 1): number {
    return text.length * 6 * scale;
  }

  toPNG(): Buffer {
    return encodePNG(this.width, this.height, this.data);
  }
}

